package com.kodewala.day12.constructors;

public class AccountHolder {
	
	// Data
	int amount;
	String account;
	String name;
	String phoneNumber;
	
	public AccountHolder(int _amount, String _account, String _name, String _phoneNumber) {
		this.amount = _amount;
		this.account = _account;
		this.name = _name;
		this.phoneNumber = _phoneNumber;	
	}
}
